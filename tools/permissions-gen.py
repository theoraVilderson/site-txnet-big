#!/usr/bin/env python3
"""Generate the permission registry from auth-handler/configs/permissions.yaml (AC-1-f).

Catalog §3.4: the permission registry is one file, the same one the gate
enforces. `auth-service` answers it to the panel (`GET /api/auth/permissions`),
so it needs the list in TypeScript, and the only way to keep that from being a
second list is to generate it. One row per key the file names, `*` aside:

    permission   the key
    area         its first segment (`tenant_billing.adjust` -> `tenant_billing`),
                 which is how the role editor groups it
    platformOnly listed under `SuperAdmin` alone — not on `grantable:` nor under
                 `user` — so no group or tenant-made role may claim it (the
                 gate's tenant ceiling, F-018-n2, ADR-0144)

Every key also needs a label and a description in English and Persian, in
`locales/backend/langs/<lang>/permissions.json` under `keys.<key>`, and every
area a label under `areas.<area>`. `--check` fails on a stale file or a missing
text. `tools/contracts.py` runs it, so a key added to the policy without its
texts fails the six checks.

    python3 tools/permissions-gen.py          write the file
    python3 tools/permissions-gen.py --check  exit 1 when stale or a text is missing
"""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "txnet-backend" / "shared-core" / "src" / "lib" / "http" / "permission-registry.generated.ts"
LOCALES = ROOT / "locales" / "backend" / "langs"
LANGS = ("en", "fa")
ALL = "*"
PLATFORM_ROLE = "SuperAdmin"


def _parse_permissions():
    """`contracts.py`'s parser — the one that reads the file exactly as the Go gate does.

    -> (role -> keys, the `grantable:` list, ADR-0144 (2)).
    """
    spec = importlib.util.spec_from_file_location("contracts", Path(__file__).parent / "contracts.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    roles, _ = module.parse_permissions()
    return roles, module.parse_grantable()


def registry() -> list[dict]:
    roles, grantable = _parse_permissions()
    held_below = grantable.union(*(keys for role, keys in roles.items() if role != PLATFORM_ROLE))
    keys = sorted((grantable.union(*roles.values())) - {ALL})
    return [{"key": k, "area": k.split(".", 1)[0], "platformOnly": k not in held_below} for k in keys]


def render() -> str:
    rows = registry()
    out = [
        "// AUTO-GENERATED by tools/permissions-gen.py from auth-handler/configs/permissions.yaml — do not edit.",
        "// Regenerate with `python3 tools/permissions-gen.py`; tools/contracts.py fails when this is stale.",
        "",
        "/** Every permission key the policy file names (`*` aside), with its area and whether only the platform may hold it. */",
        "export const PERMISSION_REGISTRY = [",
    ]
    for row in rows:
        out.append(f"  {{ permission: {json.dumps(row['key'])}, area: {json.dumps(row['area'])}, platformOnly: {'true' if row['platformOnly'] else 'false'} }},")
    out += [
        "] as const;",
        "",
        "/** A permission key the registry names. */",
        "export type RegisteredPermission = (typeof PERMISSION_REGISTRY)[number]['permission'];",
        "",
    ]
    return "\n".join(out)


def missing_texts() -> list[str]:
    problems = []
    rows = registry()
    for lang in LANGS:
        path = LOCALES / lang / "permissions.json"
        if not path.exists():
            problems.append(f"{path.relative_to(ROOT)} is missing")
            continue
        tree = json.loads(path.read_text(encoding="utf-8"))
        for area in sorted({r["area"] for r in rows}):
            if not tree.get("areas", {}).get(area, {}).get("label"):
                problems.append(f"{lang}: no areas.{area}.label")
        for row in rows:
            node = tree.get("keys", {})
            for segment in row["key"].split("."):
                node = node.get(segment, {}) if isinstance(node, dict) else {}
            for field in ("label", "description"):
                if not node.get(field):
                    problems.append(f"{lang}: no keys.{row['key']}.{field}")
    return problems


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        problems = missing_texts()
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            problems.insert(0, f"{OUT.relative_to(ROOT)} is stale — run python3 tools/permissions-gen.py and commit it")
        for p in problems:
            print(f"ERROR {p}")
        return 1 if problems else 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
